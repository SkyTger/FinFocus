"""Единственный источник правды о версии приложения.

Версия задана константой в модуле кода, а не вычисляется в рантайме.
Причина — запуск из PyInstaller-бандла, где привычные способы узнать
версию не работают:

- ``importlib.metadata.version("finfocus")`` — приложение не ставится
  как дистрибутив (нет ``pip install``, нет ``*.dist-info``), запуск
  идёт из исходников либо из бандла, поэтому метаданных нет вообще;
- data-файл (``VERSION``, ``version.json``) — файл рядом с исходником
  в бандл сам по себе не попадает, его пришлось бы прописывать в
  ``datas`` внутри ``finfocus.spec``, то есть держать синхронными два
  места вместо одного;
- ``git describe`` в рантайме — в бандле нет каталога ``.git``, а на
  машине пользователя нет и самого ``git``.

Модуль кода лишён этих проблем: PyInstaller укладывает его в PYZ
вместе с остальным кодом, а чтение версии — обычный импорт.

УСЛОВИЕ ДОСТИЖИМОСТИ (важно при правках UI!)
--------------------------------------------
В бандл попадает только то, что PyInstaller видит по СТАТИЧЕСКОМУ
графу импортов от ``run.py``. Для этого модуля цепочка сейчас
единственная::

    run.py -> app.main -> app.components.profile_modal
                              -> from app import __version__

То есть модуль достижим ровно до тех пор, пока строка версии живёт в
окне профиля. Если убрать её оттуда, не перенеся импорт в другое
достижимое место, ``app/version.py`` молча выпадет из бандла: в
исходниках всё продолжит работать, а собранное приложение упадёт на
импорте. Ошибка проявится только у пользователя бандла — тестами
из исходников она не ловится.

БАМП ВЕРСИИ
-----------
Константа правится РУКАМИ и одновременно с проставлением git-тега:
``__version__ = "X.Y.Z"`` здесь и ``git tag vX.Y.Z`` в репозитории.
Соответствие тега и константы проверяет ``tests/test_version.py``
(там, где ``.git`` доступен).

Имя файла — ``version.py``, НЕ ``__version__.py``: во втором случае
атрибут ``app.__version__`` означал бы то строку, то подмодуль, в
зависимости от порядка импортов.
"""

